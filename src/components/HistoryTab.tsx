import React from 'react';
import { History, CheckCircle2, TrendingDown, TrendingUp, AlertCircle } from 'lucide-react';
import { TradeHistoryItem } from '../types/forex';

interface HistoryTabProps {
  history: TradeHistoryItem[];
  onClearHistory: () => void;
}

export const HistoryTab: React.FC<HistoryTabProps> = ({ history, onClearHistory }) => {
  const totalPipsGained = history.reduce((acc, h) => acc + h.pipsResult, 0);
  const totalUsdGained = history.reduce((acc, h) => acc + h.usdResult, 0);
  const winCount = history.filter((h) => h.status !== 'SL HIT').length;
  const winRate = history.length > 0 ? Math.round((winCount / history.length) * 100) : 100;

  return (
    <div className="space-y-4">
      {/* Top Stats Banner */}
      <div className="bg-[#1A1A1A] border border-[#2A2A2A] rounded-xl p-3.5 space-y-3">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-2">
            <History className="w-4 h-4 text-[#00FF88]" />
            <h2 className="text-white font-extrabold text-xs uppercase tracking-wider">
              WAT SIGNAL EXECUTION LOG
            </h2>
          </div>
          {history.length > 0 && (
            <button
              onClick={onClearHistory}
              className="text-[10px] text-gray-400 hover:text-white underline cursor-pointer"
            >
              Clear Log
            </button>
          )}
        </div>

        <div className="grid grid-cols-3 gap-2 text-center font-mono">
          <div className="bg-[#121212] border border-[#262626] rounded-lg p-2">
            <span className="text-[10px] text-gray-400 uppercase block">Win Rate</span>
            <span className="text-base font-black text-[#00FF88] tabular-nums">
              {winRate}%
            </span>
          </div>

          <div className="bg-[#121212] border border-[#262626] rounded-lg p-2">
            <span className="text-[10px] text-gray-400 uppercase block">Total Pips</span>
            <span className="text-base font-black text-[#00FF88] tabular-nums">
              +{totalPipsGained}
            </span>
          </div>

          <div className="bg-[#121212] border border-[#262626] rounded-lg p-2">
            <span className="text-[10px] text-gray-400 uppercase block">Est Profit</span>
            <span className="text-base font-black text-[#00FF88] tabular-nums">
              +${totalUsdGained.toFixed(2)}
            </span>
          </div>
        </div>
      </div>

      {/* Signal Log List */}
      <div className="space-y-2">
        {history.length === 0 ? (
          <div className="bg-[#1A1A1A] border border-[#2A2A2A] rounded-xl p-8 text-center text-gray-400 text-xs">
            <AlertCircle className="w-8 h-8 text-gray-600 mx-auto mb-2" />
            <p className="font-semibold text-gray-300">No Historical Signals Yet</p>
            <p className="text-[11px] text-gray-400 mt-1">
              Active signals generated by the WAT Engine will be logged here with verified TP execution.
            </p>
          </div>
        ) : (
          history.map((item) => (
            <div
              key={item.id}
              className="bg-[#1A1A1A] border border-[#2A2A2A] rounded-xl p-3 flex flex-col gap-2 text-xs font-mono"
            >
              <div className="flex items-center justify-between">
                <div className="flex items-center gap-2">
                  {item.signalType === 'SELL' ? (
                    <span className="bg-[#FF3333]/20 border border-[#FF3333] text-[#FF3333] px-2 py-0.5 rounded text-[10px] font-black uppercase">
                      SELL
                    </span>
                  ) : (
                    <span className="bg-[#00FF88]/20 border border-[#00FF88] text-[#00FF88] px-2 py-0.5 rounded text-[10px] font-black uppercase">
                      BUY
                    </span>
                  )}
                  <span className="text-white font-bold">
                    @ ${item.entryPrice.toFixed(2)}
                  </span>
                </div>

                <span className="text-[#00FF88] font-black text-xs tabular-nums">
                  +{item.pipsResult} pips (+${item.usdResult.toFixed(2)})
                </span>
              </div>

              <div className="flex items-center justify-between text-[10px] text-gray-400 pt-1 border-t border-white/5">
                <span>WAT: {item.timestampWAT}</span>
                <span className="text-gray-300">
                  SL: ${item.stopLossPrice.toFixed(2)} | TP1: ${item.tp1Price.toFixed(2)}
                </span>
                <span className="text-[#00FF88] font-bold">
                  {item.status} ✅
                </span>
              </div>
            </div>
          ))
        )}
      </div>
    </div>
  );
};
